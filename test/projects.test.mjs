test('workspace navigation selects the right project section and remembers the theme', () => {
  const html = fs.readFileSync(new URL('../src/workspace.html', import.meta.url), 'utf8');
  const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
  const navSource = script.slice(script.indexOf('const viewInfo'), script.indexOf('function applyTheme'));
  const panels = ['overview', 'brain', 'tickets', 'settings'].map((name) => ({ dataset: { panel: name }, hidden: false }));
  const navs = ['projects', 'overview', 'brain', 'tickets', 'settings'].map((name) => ({ dataset: { view: name }, attrs: {}, setAttribute(k, v) { this.attrs[k] = v; }, removeAttribute(k) { delete this.attrs[k]; } }));
  const nodes = Object.fromEntries(['#page-eyebrow', '#page-title', '#page-description', '#project-list', '#show-add'].map((key) => [key, { textContent: '', hidden: false }]));
  const detail = { hidden: false, querySelectorAll: () => panels }, message = { textContent: '' };
  const context = { selectedProject: { name: 'Doctor' }, activeView: 'projects', detail, message,
    document: { querySelector: (key) => nodes[key], querySelectorAll: () => navs } };
  const setView = vm.runInNewContext(`${navSource}\nsetView`, context);
  setView('brain');
  assert.equal(nodes['#page-title'].textContent, 'Project Brain');
  assert.equal(nodes['#page-eyebrow'].textContent, 'Doctor');
  assert.equal(panels.find((p) => p.dataset.panel === 'brain').hidden, false);
  assert.equal(panels.find((p) => p.dataset.panel === 'tickets').hidden, true);
  assert.equal(navs.find((n) => n.dataset.view === 'brain').attrs['aria-current'], 'page');
  setView('projects');
  assert.equal(detail.hidden, true);
  assert.equal(nodes['#project-list'].hidden, false);
  const themeSource = script.slice(script.indexOf('function applyTheme'), script.indexOf('let savedTheme'));
  const toggle = { textContent: '', setAttribute(k, v) { this[k] = v; } }, stored = {};
  const themeContext = { document: { documentElement: { dataset: {} }, querySelector: () => toggle }, localStorage: { setItem(k, v) { stored[k] = v; } } };
  const applyTheme = vm.runInNewContext(`${themeSource}\napplyTheme`, themeContext);
  applyTheme('dark');
  assert.equal(themeContext.document.documentElement.dataset.theme, 'dark');
  assert.equal(stored['agent-pipeline-theme'], 'dark');
  assert.match(toggle['aria-label'], /light/);
});

test('registers separate projects without touching their contents and removes only metadata', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'pipeline-projects-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const one = path.join(root, 'one');
  const two = path.join(root, 'two');
  fs.mkdirSync(one);
  fs.mkdirSync(two);
  fs.writeFileSync(path.join(one, 'keep.txt'), 'keep');
  const registry = projectRegistry(path.join(root, 'registry', 'projects.json'));
  const first = registry.add({ directory: one, name: 'One' });
  const second = registry.add({ directory: two, name: 'Two' });
  assert.notEqual(first.id, second.id);
  assert.equal(registry.resolve(first.id).path, fs.realpathSync(one));
  assert.deepEqual(registry.list().map((p) => p.name), ['One', 'Two']);
  assert.throws(() => registry.add({ directory: one }), /already registered/);
  assert.throws(() => registry.add({ directory: 'relative' }), /absolute/);
  registry.remove(first.id);
  assert.equal(fs.readFileSync(path.join(one, 'keep.txt'), 'utf8'), 'keep');
  assert.throws(() => registry.resolve(first.id), /not found/);
  assert.equal(registry.resolve(second.id).name, 'Two');
});

test('guided setup preserves existing files and requires an explicit QA command', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'pipeline-setup-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.writeFileSync(path.join(root, 'AGENTS.md'), 'existing guidance');
  assert.throws(() => setupWorkspaceProject(root, { provider: 'codex', tracker: 'file', vcs: 'none', qaCommand: '' }), /QA command/);
  assert.equal(fs.existsSync(path.join(root, 'pipeline.config.json')), false);
  const result = setupWorkspaceProject(root, { provider: 'claude', tracker: 'file', vcs: 'git', qaCommand: 'npm test' });
  assert.ok(result.kept.includes('AGENTS.md'));
  assert.equal(fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8'), 'existing guidance');
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(root, 'tickets.json'), 'utf8')), []);
  const cfg = loadConfig(path.join(root, 'pipeline.config.json'));
  assert.equal(cfg.agent.provider, 'claude');
  assert.equal(cfg.vcs.push, false);
  assert.equal(cfg.qa.command, 'npm test');
  assert.throws(() => setupWorkspaceProject(root, { provider: 'codex', tracker: 'file', vcs: 'none', qaCommand: 'npm test' }), /already exists/);
  assert.equal(loadConfig(path.join(root, 'pipeline.config.json')).agent.provider, 'claude');
  const saved = agentSettings(root);
  agentSettings(root, { version: saved.version, code: 'codex', plan: 'claude', brain: '' });
  const updated = loadConfig(path.join(root, 'pipeline.config.json'));
  assert.equal(updated.agent.provider, 'codex');
  assert.equal(updated.agent.plan.provider, 'claude');
  assert.equal(updated.qa.command, 'npm test');
  assert.throws(() => agentSettings(root, { version: saved.version, code: 'cursor', plan: '', brain: '' }), /changed since/);
  assert.equal(loadConfig(path.join(root, 'pipeline.config.json')).agent.provider, 'codex');
});

test('guided setup supports explicit custom agents', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'pipeline-custom-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const common = { provider: 'custom', tracker: 'file', vcs: 'none', qaCommand: 'npm test' };
  assert.throws(() => setupWorkspaceProject(root, { ...common, customCommand: 'agent', customArgs: 'bad', promptMode: 'stdin' }), /custom command/);
  assert.throws(() => setupWorkspaceProject(root, { ...common, customCommand: 'agent', customArgs: [], promptMode: 'pointer' }), /Pointer-mode/);
  setupWorkspaceProject(root, { ...common, customCommand: 'my-agent', customArgs: ['--prompt', '{promptPointer}'], promptMode: 'pointer' });
  const cfg = loadConfig(path.join(root, 'pipeline.config.json'));
  assert.equal(cfg.agent.providers.custom.command, 'my-agent');
  assert.deepEqual(cfg.agent.providers.custom.args, ['--prompt', '{promptPointer}']);
  assert.ok(agentSettings(root).configured.includes('custom'));
});

test('pipeline settings preserve protected values and reject stale writes', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'pipeline-settings-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  setupWorkspaceProject(root, { provider: 'codex', tracker: 'file', vcs: 'none', qaCommand: 'run token=secretvalue' });
  const settings = pipelineSettings(root);
  assert.equal(settings.values.qa.command, null);
  pipelineSettings(root, { version: settings.version, values: { qa: { command: null }, knowledge: { maxPromptContextTokens: 3000 } } });
  const cfg = loadConfig(path.join(root, 'pipeline.config.json'));
  assert.equal(cfg.qa.command, 'run token=secretvalue');
  assert.equal(cfg.agent.provider, 'codex');
  assert.equal(cfg.knowledge.maxPromptContextTokens, 3000);
  assert.throws(() => pipelineSettings(root, { version: settings.version, values: { knowledge: { maxPromptContextTokens: 4000 } } }), /changed since/);
  const next = pipelineSettings(root);
  assert.throws(() => pipelineSettings(root, { version: next.version, values: { vcs: { push: 'yes' } } }), /true or false/);
});

